import 'dart:convert';

import 'package:drift/drift.dart' show Value, Variable;
import 'package:flutter/services.dart' show rootBundle;
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:ironyx/core/database/app_database.dart';
import 'package:ironyx/core/database/daos/exercise_dao.dart';
import 'package:ironyx/core/providers.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// The version of the bundled seed, so these tests need no edit on a bump.
Future<int> bundledSeedVersion() async {
  final Map<String, dynamic> seed = jsonDecode(
    await rootBundle.loadString('assets/data/exercises_seed.json'),
  ) as Map<String, dynamic>;
  return seed['seedVersion'] as int;
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  // Unreleased seeds on debug builds (22 is on the owner's phone): 21 and
  // 22 described the Lean-In Lateral Raise as leaning towards the post,
  // with no picture and no other name; 19 had a different picture. The
  // owner settled on the lean-away setup its Gemini picture shows, so a
  // reseed must bring the lean-away steps, the alias and exactly the two
  // new pictures, and keep workouts.
  for (final int oldVersion in <int>[19, 21, 22]) {
    test(
        'seed $oldVersion lean-in raise gets the lean-away steps and its '
        'pictures without losing workouts', () async {
      SharedPreferences.setMockInitialValues(<String, Object>{
        'exercise_seed_version': oldVersion,
      });
      final prefs = await SharedPreferences.getInstance();
      final database = AppDatabase.forTesting();
      final container = ProviderContainer(overrides: [
        appDatabaseProvider.overrideWithValue(database),
        sharedPreferencesProvider.overrideWithValue(prefs),
      ]);
      addTearDown(() async {
        container.dispose();
        await database.close();
      });

      await database.into(database.exercisesTable).insert(
            ExercisesTableCompanion.insert(
              id: 'ex_313',
              slug: 'lean-in-lateral-raise',
              name: 'Lean-In Lateral Raise',
              category: 'strength',
              difficulty: 'beginner',
              movementPattern: 'horizontalPush',
              seedVersion: oldVersion,
            ),
          );
      await database.into(database.exerciseInstructionsTable).insert(
            ExerciseInstructionsTableCompanion.insert(
              id: 'old-step',
              exerciseId: 'ex_313',
              stepNumber: 1,
              instruction: 'Lean your body towards the post',
            ),
          );
      if (oldVersion == 19) {
        await database.into(database.exerciseMediaTable).insert(
              ExerciseMediaTableCompanion.insert(
                id: 'old-image',
                exerciseId: 'ex_313',
                type: 'image',
                localAsset:
                    const Value('assets/images/exercises/ironyx/old.jpg'),
              ),
            );
      }
      await database.into(database.workoutsTable).insert(
            WorkoutsTableCompanion.insert(
              id: 'workout',
              startedAt: DateTime.utc(2026),
            ),
          );
      await database.into(database.workoutExercisesTable).insert(
            WorkoutExercisesTableCompanion.insert(
              id: 'workout-exercise',
              workoutId: 'workout',
              exerciseId: 'ex_313',
              orderIndex: 0,
            ),
          );

      await container.read(exerciseSeederProvider.future);
      final detail = await ExerciseDao(database).getWithDetails('ex_313');
      expect(detail, isNotNull);
      expect(detail!.instructions.first.instruction,
          contains('lean away from it'));
      expect(
        detail.instructions.map((s) => s.instruction.toLowerCase()),
        everyElement(isNot(contains('towards'))),
      );
      expect(detail.aliases, contains('Lean-Away Lateral Raise'));
      // Exactly the two new pictures: an old row is replaced, not kept.
      expect(detail.media, hasLength(2));
      for (int i = 0; i < 2; i++) {
        expect(detail.media[i].localAsset,
            'assets/images/exercises/ironyx/lean-in-lateral-raise_$i.jpg');
        expect(detail.media[i].license,
            'Generated by the Ironyx owner with Google Gemini');
        expect(detail.media[i].source, 'scripts/prepare_owner_images.py');
      }
      final row = await database.customSelect(
        'SELECT exercise_id FROM workout_exercises_table WHERE id = ?',
        variables: [Variable.withString('workout-exercise')],
      ).getSingle();
      expect(row.read<String>('exercise_id'), 'ex_313');
      expect(prefs.getInt('exercise_seed_version'), await bundledSeedVersion());
    });
  }

  // Unreleased seeds 20 and 21 (on debug builds, including the owner's
  // phone) carried other pictures or provenance at the same file names. A
  // reseed has to replace those rows, not add to them, and keep workouts.
  for (final (int version, String id, String slug, String name, String old)
      in <(int, String, String, String, String)>[
    (
      20,
      'ex_312',
      'behind-the-body-cable-curl',
      'Behind-the-Body Cable Curl',
      'scripts/draw_exercise_illustrations.py',
    ),
    (
      21,
      'ex_312',
      'behind-the-body-cable-curl',
      'Behind-the-Body Cable Curl',
      'scripts/prepare_cable_curl_images.py',
    ),
    (
      21,
      'ex_314',
      'banded-hip-abduction',
      'Banded Hip Abduction',
      'scripts/draw_exercise_illustrations.py',
    ),
  ]) {
    test(
        'seed $version $slug pictures are replaced by the owner image with '
        'its own licence, keeping workouts', () async {
      SharedPreferences.setMockInitialValues(<String, Object>{
        'exercise_seed_version': version,
      });
      final prefs = await SharedPreferences.getInstance();
      final database = AppDatabase.forTesting();
      final container = ProviderContainer(overrides: [
        appDatabaseProvider.overrideWithValue(database),
        sharedPreferencesProvider.overrideWithValue(prefs),
      ]);
      addTearDown(() async {
        container.dispose();
        await database.close();
      });

      await database.into(database.exercisesTable).insert(
            ExercisesTableCompanion.insert(
              id: id,
              slug: slug,
              name: name,
              category: 'strength',
              difficulty: 'beginner',
              movementPattern: 'isolation',
              seedVersion: version,
            ),
          );
      for (int i = 0; i < 2; i++) {
        await database.into(database.exerciseMediaTable).insert(
              ExerciseMediaTableCompanion.insert(
                id: 'old-picture-$i',
                exerciseId: id,
                type: 'image',
                localAsset:
                    Value('assets/images/exercises/ironyx/${slug}_$i.jpg'),
                sortOrder: Value(i),
                license: const Value('Original work, written for Ironyx'),
                source: Value(old),
              ),
            );
      }
      await database.into(database.workoutsTable).insert(
            WorkoutsTableCompanion.insert(
              id: 'workout',
              startedAt: DateTime.utc(2026),
            ),
          );
      await database.into(database.workoutExercisesTable).insert(
            WorkoutExercisesTableCompanion.insert(
              id: 'workout-exercise',
              workoutId: 'workout',
              exerciseId: id,
              orderIndex: 0,
            ),
          );

      await container.read(exerciseSeederProvider.future);

      final detail = await ExerciseDao(database).getWithDetails(id);
      expect(detail, isNotNull);
      expect(detail!.exercise.slug, slug, reason: 'the seed id moved');
      // Exactly the two new rows: the old ones are gone, not duplicated.
      expect(detail.media, hasLength(2));
      for (int i = 0; i < 2; i++) {
        final media = detail.media[i];
        expect(media.sortOrder, i);
        expect(
            media.localAsset, 'assets/images/exercises/ironyx/${slug}_$i.jpg');
        expect(media.license,
            'Generated by the Ironyx owner with ChatGPT (OpenAI)');
        expect(media.source, 'scripts/prepare_owner_images.py');
      }
      final row = await database.customSelect(
        'SELECT exercise_id FROM workout_exercises_table WHERE id = ?',
        variables: [Variable.withString('workout-exercise')],
      ).getSingle();
      expect(row.read<String>('exercise_id'), id);
      expect(prefs.getInt('exercise_seed_version'), await bundledSeedVersion());
    });
  }

  test('seeds every exercise from the bundled asset', () async {
    SharedPreferences.setMockInitialValues(<String, Object>{});
    final prefs = await SharedPreferences.getInstance();
    final database = AppDatabase.forTesting();
    final container = ProviderContainer(
      overrides: [
        appDatabaseProvider.overrideWithValue(database),
        sharedPreferencesProvider.overrideWithValue(prefs),
      ],
    );

    addTearDown(() async {
      container.dispose();
      await database.close();
    });

    await container.read(exerciseSeederProvider.future);
    final exercises = await ExerciseDao(database).watchAll().first;

    // Compared against the asset rather than a hardcoded count. The
    // catalogue is regenerated by scripts/build_exercise_seed.py, so a
    // literal here only ever records how many exercises existed the day
    // the test was written — and fails for the one reason that does not
    // matter. What matters is that the seeder lands *everything* in the
    // file: a partial seed is how the library silently loses exercises.
    final Map<String, dynamic> seed = jsonDecode(
      await rootBundle.loadString('assets/data/exercises_seed.json'),
    ) as Map<String, dynamic>;
    final Set<String> expected = <String>{
      for (final dynamic raw in seed['exercises'] as List<dynamic>)
        (raw as Map<String, dynamic>)['name'] as String,
    };

    expect(expected, isNotEmpty, reason: 'the seed asset itself is empty');
    expect(
      exercises.map((summary) => summary.exercise.name).toSet(),
      equals(expected),
    );
  });
}
