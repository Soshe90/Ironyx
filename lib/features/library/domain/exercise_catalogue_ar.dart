/// Kept out of the ARB files on purpose. These are catalogue *data*, not UI
/// chrome: they are keyed by the stable slugs and ids the seed defines, they
/// change when the seed changes rather than when the copy does, and adding
/// 150 exercise names to `app_ar.arb` would bury the interface strings that
/// actually need re-reading whenever the UI changes. The fixed enum
/// vocabularies (category, difficulty, movement pattern) *are* in the ARB,
/// because those are wording rather than data.
///
/// Anything absent falls back to the English name stored in the database.
/// That is also what user-created exercises get: they have no slug in this
/// table, and their name is one the user typed themselves.
///
/// `test/unit/exercise_catalogue_ar_test.dart` checks every key here against
/// the seed, so a reseed that renames a slug fails the suite rather than
/// silently reverting those rows to English.
