def label_mask(rgb: np.ndarray, spec: OwnerImage) -> np.ndarray:
    """Pixels that belong to the labels: their text and leader lines."""
    height, width, _ = rgb.shape
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY).astype(np.int16)
    background = int(np.median(gray[spec.crop_top + 5 : spec.crop_top + 40, 5:40]))
    mask = np.zeros((height, width), np.uint8)

    # The label areas are plain background apart from the text, so anything
    # visibly different from it is text, including its soft edges.
    for x0, y0, x1, y1 in spec.text_boxes:
        region = np.abs(gray[y0:y1, x0:x1] - background) > 4
        mask[y0:y1, x0:x1][region] = 255

    mask = cv2.dilate(mask, np.ones((3, 3), np.uint8), iterations=2)

    # Leader lines are straight and near-black, so each is traced and
    # masked exactly: a thin strip and the dot it ends in. A wide band
    # instead caught the outlines of the arm and hip it crosses, and the
    # fill then blurred them.
    for start, end in spec.leader_lines:
        slope, intercept = trace_line(gray, start, end)
        x0, x1 = sorted((start[0], end[0]))
        a = (x0, round(slope * x0 + intercept))
        b = (x1, round(slope * x1 + intercept))
        cv2.line(mask, a, b, 255, thickness=LINE_WIDTH)
        body_end = a if end[0] == x0 else b
        cv2.circle(mask, body_end, DOT_RADIUS, 255, thickness=-1)
    return mask


# The drawn lines are about 2-3 px wide with soft edges, ending in a dot.
LINE_WIDTH = 5
DOT_RADIUS = 5


def trace_line(gray: np.ndarray, start: Point, end: Point) -> tuple[float, float]:
    """Fit y = slope * x + intercept to the darkest pixels near a rough line."""
    xs, ys = [], []
    for x in range(min(start[0], end[0]), max(start[0], end[0]) + 1):
        t = (x - start[0]) / (end[0] - start[0])
        guess = round(start[1] + t * (end[1] - start[1]))
        column = gray[guess - 8 : guess + 9, x]
        if column.min() < 70:
            xs.append(x)
            ys.append(guess - 8 + int(column.argmin()))
    xs_arr, ys_arr = np.array(xs, float), np.array(ys, float)
    if len(xs_arr) < 10:
        raise SystemExit(f"could not trace the leader line {start} -> {end}")
    slope, intercept = np.polyfit(xs_arr, ys_arr, 1)
    # Drop points on other dark detail (trouser edges, shadows) and refit.
    keep = np.abs(ys_arr - (slope * xs_arr + intercept)) <= 2
    if keep.sum() < 10:
        raise SystemExit(f"leader line {start} -> {end} is not straight")
    slope, intercept = np.polyfit(xs_arr[keep], ys_arr[keep], 1)
    return float(slope), float(intercept)


def fit(frame: Image.Image, background: tuple[int, int, int]) -> Image.Image:
    scale = SAFE_HEIGHT / frame.height
    resized = frame.resize(
        (round(frame.width * scale), SAFE_HEIGHT), Image.Resampling.LANCZOS
    )
    if resized.width > OUT_SIZE[0]:
        raise SystemExit(f"frame is too wide after scaling: {resized.width}px")
    canvas = Image.new("RGB", OUT_SIZE, background)
    canvas.paste(
        resized,
        ((OUT_SIZE[0] - resized.width) // 2, (OUT_SIZE[1] - resized.height) // 2),
    )
    return canvas


def prepare(spec: OwnerImage) -> None:
    source = SOURCES / spec.source
    image = Image.open(source).convert("RGB")
    if image.size != spec.size:
        raise SystemExit(
            f"{source.name} is {image.size}, expected {spec.size}; the "
            "label positions in this script would no longer match"
        )

    rgb = np.asarray(image)
    bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    cleaned = cv2.inpaint(bgr, label_mask(rgb, spec), 5, cv2.INPAINT_TELEA)
    clean = Image.fromarray(cv2.cvtColor(cleaned, cv2.COLOR_BGR2RGB))

    width, height = image.size
    background = clean.getpixel((5, spec.crop_top + 5))
    frames = [
        clean.crop((0, spec.crop_top, spec.split_x, height)),
        clean.crop((spec.split_x, spec.crop_top, width, height)),
    ]
    for index, frame in enumerate(frames):
        fit(frame, background).save(
            OUT / f"{spec.stem}_{index}.jpg", quality=80, optimize=True
        )
    print(f"Wrote {spec.stem}_0.jpg and {spec.stem}_1.jpg")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for spec in IMAGES:
        prepare(spec)


if __name__ == "__main__":
    main()
